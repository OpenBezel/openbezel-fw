#!/usr/bin/env python3
"""gen_logo - rasterize an SVG (or PNG) logo and emit logo.c / logo.h (build/gen/) for the OSD.

The RTD2556 OSD is a character/glyph tiling engine (12x18 cells), so the logo is split
into 12x18 tiles.  Each tile is 1 bpp (opaque / transparent); the per-tile foreground
color (white or the orange accent) is carried in the OSD character command, so glyphs
are de-duplicated by their 1-bpp mask only.  Tile 0 is always the blank tile.

  gen_logo.py --svg images/openbezel_wordmark.svg --out build/gen/logo.c
              [--width N] [--height N]   (default: the image's natural size)

Palette indices used (see osd.c): 0 = transparent, LOGO_FG_WHITE, LOGO_FG_ORANGE.
Needs Pillow, and rsvg-convert for SVG input.
"""
import argparse, os, subprocess, sys
from PIL import Image

TILE_W, TILE_H = 12, 18
WHITE = (255, 255, 255)
ORANGE = (255, 176, 32)
FG_WHITE, FG_ORANGE = 7, 1          # OSD palette indices (osd.c sets LUT[1] = orange)


def rasterize(path, w, h):
    if path.lower().endswith(".svg"):
        import tempfile
        png = tempfile.mktemp(suffix=".png")
        cmd = ["rsvg-convert", path, "-o", png]
        if w: cmd += ["-w", str(w)]
        if h: cmd += ["-h", str(h)]
        subprocess.check_call(cmd)
        im = Image.open(png).convert("RGBA")
        os.unlink(png)
    else:
        im = Image.open(path).convert("RGBA")
        if w or h:
            im = im.resize((w or im.width, h or im.height), Image.LANCZOS)
    return im


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--svg", "--image", dest="image", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--width", type=int)
    p.add_argument("--height", type=int)
    p.add_argument("--name", default="logo")
    a = p.parse_args()
    im = rasterize(a.image, a.width, a.height)
    W, H = im.size
    cols = (W + TILE_W - 1) // TILE_W
    rows = (H + TILE_H - 1) // TILE_H
    px = im.load()

    def opaque(x, y):
        return x < W and y < H and px[x, y][3] >= 128

    def fg_of(x, y):
        r, g, b, _ = px[x, y]
        # nearest of white / orange by simple distance
        dw = (r - 255) ** 2 + (g - 255) ** 2 + (b - 255) ** 2
        do = (r - ORANGE[0]) ** 2 + (g - ORANGE[1]) ** 2 + (b - ORANGE[2]) ** 2
        return FG_ORANGE if do < dw else FG_WHITE

    glyphs = [[0] * 27]          # glyph 0 = blank
    glyph_index = {bytes(27): 0}
    tilemap, tilefg = [], []
    for ty in range(rows):
        for tx in range(cols):
            words = []
            fg_votes = {}
            for wi in range(TILE_H // 2):
                b0 = b1 = 0
                for col in range(TILE_W):
                    x = tx * TILE_W + col
                    y0, y1 = ty * TILE_H + wi * 2, ty * TILE_H + wi * 2 + 1
                    if opaque(x, y0):
                        b0 |= 1 << (TILE_W - 1 - col); f = fg_of(x, y0); fg_votes[f] = fg_votes.get(f, 0) + 1
                    if opaque(x, y1):
                        b1 |= 1 << (TILE_W - 1 - col); f = fg_of(x, y1); fg_votes[f] = fg_votes.get(f, 0) + 1
                val = b1 | (b0 << 12)
                words += [val & 0xFF, (val >> 8) & 0xFF, (val >> 16) & 0xFF]
            key = bytes(words)
            gi = glyph_index.get(key)
            if gi is None:
                gi = len(glyphs); glyph_index[key] = gi; glyphs.append(words)
            tilemap.append(gi)
            tilefg.append(max(fg_votes, key=fg_votes.get) if fg_votes else FG_WHITE)

    if len(glyphs) > 256:
        sys.exit("logo needs %d unique tiles (>256); pass a smaller --width/--height "
                 "(the OSD character select is 8-bit)" % len(glyphs))

    up = a.name.upper()
    hdr = os.path.splitext(a.out)[0] + ".h"
    h = ["/* generated by tools/gen_logo.py from %s - do not edit */" % os.path.basename(a.image),
         "#ifndef %s_LOGO_H" % up, "#define %s_LOGO_H" % up, "", '#include "ob_types.h"', "",
         "/* %dx%d logo as %dx%d tiles of 12x18 px, 1 bpp; %d unique glyphs (0 = blank) */" % (W, H, cols, rows, len(glyphs)),
         "#define %s_COLS %d" % (up, cols),
         "#define %s_ROWS %d" % (up, rows),
         "#define %s_W %d" % (up, cols * TILE_W),
         "#define %s_H %d" % (up, rows * TILE_H),
         "#define %s_NGLYPH %d" % (up, len(glyphs)), "",
         "/* The glyph, tilemap and palette arrays are not compiled in: they live in the flash",
         " * asset partition.  %s is their source, read by" % os.path.basename(a.out),
         " * tools/gen_assets.py, which also precomputes the per-cell character-command stream. */",
         "", "#endif  /* %s_LOGO_H */" % up, ""]
    open(hdr, "w").write("\n".join(h))

    o = ["/* generated by tools/gen_logo.py from %s - do not edit */" % os.path.basename(a.image),
         '#include "%s"' % os.path.basename(hdr), "",
         "/* Per-tile foreground palette index in %s_tile_fg; glyph mask in %s_glyphs (font format). */" % (a.name, a.name),
         "const __code u8 %s_glyphs[%d][27] = {" % (a.name, len(glyphs))]
    for g in glyphs:
        o.append("    {" + ", ".join("0x%02X" % b for b in g) + "},")
    o.append("};")
    o.append("const __code u8 %s_tilemap[%d] = {" % (a.name, cols * rows))
    for r in range(rows):
        o.append("    " + ", ".join("%3d" % tilemap[r * cols + c] for c in range(cols)) + ",")
    o.append("};")
    o.append("const __code u8 %s_tile_fg[%d] = {" % (a.name, cols * rows))
    for r in range(rows):
        o.append("    " + ", ".join("%d" % tilefg[r * cols + c] for c in range(cols)) + ",")
    o.append("};")
    open(a.out, "w").write("\n".join(o) + "\n")



if __name__ == "__main__":
    main()
