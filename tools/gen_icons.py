#!/usr/bin/env python3
"""gen_icons - render a theme icon set (themes/icons/<set>/*.svg) to OSD glyphs.

Run by the build (gen/meson.build; needs Pillow and rsvg-convert): writes the set as C,
which tools/gen_theme.py reads, and with --preview a PNG of the icons in a demo palette,
enlarged, for review.

The SVGs are drawn in four placeholder colors, mapped to the icon roles by set.json
("roles"); a color scheme gives the roles their real colors, so one icon set works
with every scheme.  Each icon is rendered at 8x and every output pixel takes the role
covering most of it (no anti-aliasing: a 4-bit glyph pixel is a palette entry, and the
low 16 entries are shared with the text colors - tools/themelib.py).

Usage: gen_icons.py themes/icons/flat --out icons_flat.c [--preview preview.png]
"""
import argparse, json, os, subprocess, sys, tempfile

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import themelib as tl

SS = 8      # supersampling


def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def render(svg, w, h):
    with tempfile.TemporaryDirectory() as d:
        png = os.path.join(d, "i.png")
        subprocess.check_call(["rsvg-convert", "-w", str(w * SS), "-h", str(h * SS), svg, "-o", png])
        return Image.open(png).convert("RGBA")


def classify(img, w, h, roles):
    """-> h rows of w LUT indices (0 = background)."""
    keys = [(hex_rgb(k), tl.lut_index(v)) for k, v in roles.items()]
    px = img.load()
    out = []
    for y in range(h):
        row = []
        for x in range(w):
            votes = {}
            for sy in range(SS):
                for sx in range(SS):
                    r, g, b, a = px[x * SS + sx, y * SS + sy]
                    if a < 128:
                        k = 0
                    else:
                        k = min(keys, key=lambda kv: sum((p - q) ** 2 for p, q in zip(kv[0], (r, g, b))))[1]
                    votes[k] = votes.get(k, 0) + 1
            row.append(max(votes, key=votes.get))
        out.append(row)
    return out


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("setdir")
    p.add_argument("--out", required=True, help="the C file")
    p.add_argument("--preview", help="also draw the icons to this PNG")
    a = p.parse_args()
    meta = json.load(open(os.path.join(a.setdir, "set.json")))
    bpp, (cw, ch) = meta["bpp"], meta["cells"]
    w, h = cw * tl.CELL_W, ch * tl.CELL_H
    blob = bytearray()
    pix = {}
    for name in meta["icons"]:
        rows = classify(render(os.path.join(a.setdir, name + ".svg"), w, h), w, h, meta["roles"])
        pix[name] = rows
        for cy in range(ch):                         # cells row-major
            for cx in range(cw):
                cell = [r[cx * tl.CELL_W:(cx + 1) * tl.CELL_W] for r in rows[cy * tl.CELL_H:(cy + 1) * tl.CELL_H]]
                blob += tl.pack_cell(cell, bpp)
    set_name = os.path.basename(os.path.normpath(a.setdir))
    with open(a.out, "w") as f:
        f.write("/* generated by tools/gen_icons.py from themes/icons/%s - do not edit */\n" % set_name)
        f.write("/* %d icons x %dx%d cells, %d-bit, %d bytes per cell: %s */\n"
                % (len(meta["icons"]), cw, ch, bpp, len(blob) // (len(meta["icons"]) * cw * ch), ", ".join(meta["icons"])))
        f.write("const unsigned char icon_glyphs[%d] = {\n" % len(blob))
        for i in range(0, len(blob), 18):
            f.write("    " + ", ".join("0x%02X" % b for b in blob[i:i + 18]) + ",\n")
        f.write("};\n")
    if not a.preview:
        return
    # preview: demo palette, 6x, on a mid-gray panel
    demo = {0: (40, 44, 52), 6: (230, 230, 235), 7: (90, 200, 120), 8: (70, 110, 200), 9: (250, 200, 60)}
    Z = 6
    prev = Image.new("RGB", ((w + 4) * len(pix) * Z, (h + 4) * Z), (25, 25, 30))
    for i, (name, rows) in enumerate(pix.items()):
        for y, r in enumerate(rows):
            for x, v in enumerate(r):
                c = demo.get(v, (255, 0, 255))
                if bpp == 1 and v:
                    c = demo[6]
                for dy in range(Z):
                    for dx in range(Z):
                        prev.putpixel(((i * (w + 4) + 2 + x) * Z + dx, (2 + y) * Z + dy), c)
    prev.save(a.preview)


if __name__ == "__main__":
    main()
