#!/usr/bin/env python3
"""gen_display_tables - generate display_tables.c (build/gen/): the display dither SRAM
contents, loaded through D_DITHER_DATA_ACCESS (port 0069) with D_DITHER_COMMON_CTRL1[7:6]
selecting the table (display.c load_dither).

  dither table     144 bytes, stock's (flash 0x136A5), held here as DITHER_TABLE - the only
                   stock data left: 3 channels x 4 distinct 20-bit patterns (8 bits set each, 2-bit
                   fields 3 and 7 always 0) placed as 4x4 Latin squares; what a pattern
                   encodes is not decoded, so no replacement is generated
  sequence table   48 bytes, a balanced shuffle of 2-bit selectors (ditherlib.sequence);
                   stock's (0x13735) has no discernible rule.  Neither dither block makes a
                   visible difference on the intouch156b panel (A/B tested), so nothing
                   finer could be judged
  temporal table   32 bytes, frame indices 0..15 as nibbles, repeated (equal to stock 0x13765)

Usage: gen_display_tables.py --out build/gen/display_tables.c [--stock-bin STOCK.bin]
"""
import argparse, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ditherlib  # noqa: E402

STOCK_DITHER, STOCK_SEQ, STOCK_TEMPORAL = 0x136A5, 0x13735, 0x13765

# The display dither table: stock's (flash 0x136A5), the one table with no known rule.
DITHER_TABLE = bytes.fromhex(
    "048cc3084fc0018e4602858d018e46048cc3084fc002858d"
    "048cc3018e46084fc002858d084fc0048cc3018e4602858d"
    "01c9860b0cc407c8c00ac24501c9860ac24507c8c00b0cc4"
    "01c9860b0cc40ac24507c8c00b0cc40ac24501c98607c8c0"
    "004fc804c30b01498e0ac245004fc804c30b01498e0ac245"
    "0ac24501498e04c30b004fc801498e004fc804c30b0ac245")
assert len(DITHER_TABLE) == 0x90


def dither_temporal():
    """Display dither temporal table: frame indices 0..15 as nibbles (low nibble first),
    the 16-frame sequence repeated four times."""
    return bytes(((2 * i + 1) & 15) << 4 | (2 * i) & 15 for i in range(0x20))


def emit(out, name, data, comment):
    out.append("/* %s */" % comment)
    out.append("const __code u8 %s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
    out.append("};")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--stock-bin", help="a stock image to compare the dither and temporal tables against")
    p.add_argument("--out", required=True)
    a = p.parse_args()
    if a.stock_bin:
        img = open(a.stock_bin, "rb").read()
        if img[STOCK_DITHER:STOCK_DITHER + 0x90] != DITHER_TABLE:
            raise SystemExit("dither_table: differs from the stock image")
        if img[STOCK_TEMPORAL:STOCK_TEMPORAL + 0x20] != dither_temporal():
            raise SystemExit("dither_temporal_table: computed table differs from stock")
    out = ["/* generated by tools/gen_display_tables.py - do not edit */",
           '#include "ob_types.h"', "",
           "/* display dither SRAM tables, loaded through D_DITHER_DATA_ACCESS (0069) with",
           "   D_DITHER_COMMON_CTRL1[7:6] dither_access selecting the table (display.c load_dither) */"]
    emit(out, "dither_table", DITHER_TABLE,
         "stock's (flash 0x%05X), 144 bytes: format not decoded (gen_display_tables.py)" % STOCK_DITHER)
    emit(out, "dither_seq_table", ditherlib.sequence(48, 0xD17E55), "ditherlib.sequence(48, 0xD17E55)")
    emit(out, "dither_temporal_table", dither_temporal(), "frame indices 0..15, repeated (dither_temporal)")
    open(a.out, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
